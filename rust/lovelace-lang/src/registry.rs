//! The builtin registry: one descriptor per function the runtime publishes.
//!
//! This is DATA, transcribed from the reference runtime's own registry (the C# plugins' builtin
//! descriptors). It feeds the envelope's functions array and the --functions / --function
//! discovery surface, so the wire, help and completion all describe a builtin the same way.

/// One builtin's declared signature and discovery metadata.
pub struct BuiltinInfo {
    /// The registered name.
    pub name: &'static str,
    /// The declared parameter names.
    pub parameters: &'static [&'static str],
    /// The smallest accepted argument count.
    pub min_arity: usize,
    /// The declared parameter count (the largest accepted count unless variadic).
    pub parameter_count: usize,
    /// Whether extra trailing arguments are accepted.
    pub variadic: bool,
    /// The plugin that registered it, when it is not core.
    pub plugin: Option<&'static str>,
    /// The published category.
    pub category: &'static str,
    /// A one-line summary, when registered.
    pub summary: Option<&'static str>,
    /// The declared return kind, when registered.
    pub return_kind: Option<&'static str>,
    /// Related builtin names.
    pub related: &'static [&'static str],
    /// Runnable examples.
    pub examples: &'static [&'static str],
}

