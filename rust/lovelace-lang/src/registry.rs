/// The descriptor registered under a name, or None.
pub fn find(name: &str) -> Option<&'static BuiltinInfo> {
    BUILTINS.iter().find(|b| b.name == name)
}

/// Every descriptor whose name contains the pattern, case-insensitively, in name order.
pub fn matching(pattern: &str) -> Vec<&'static BuiltinInfo> {
    let needle = pattern.to_ascii_lowercase();
    BUILTINS
        .iter()
        .filter(|b| b.name.to_ascii_lowercase().contains(&needle))
        .collect()
}

