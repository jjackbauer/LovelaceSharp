/// The registered names closest to `queried`, best first (rank, then ordinal name, at most three).
pub fn suggest(queried: &str) -> Vec<String> {
    let mut ranked: Vec<(u8, &'static str)> = Vec::new();
    for builtin in BUILTINS {
        let rank = name_rank(builtin.name, queried);
        if rank >= 0 {
            ranked.push((rank as u8, builtin.name));
        }
    }
    if let Some((_, targets)) = SYNONYMS
        .iter()
        .find(|(word, _)| word.eq_ignore_ascii_case(queried))
    {
        for target in *targets {
            if find(target).is_some() {
                ranked.push((0, target));
            }
        }
    }
    ranked.sort_by(|a, b| a.0.cmp(&b.0).then_with(|| a.1.cmp(b.1)));
    let mut out: Vec<String> = Vec::new();
    for (_, name) in ranked {
        if !out.iter().any(|existing| existing == name) {
            out.push(name.to_string());
        }
        if out.len() == MAX_SUGGESTIONS {
            break;
        }
    }
    out
}

/// The syntax notes that apply to `queried` (empty when none do).
pub fn hints(queried: &str) -> Vec<String> {
    SYNTAX_HINTS
        .iter()
        .find(|(word, _)| word.eq_ignore_ascii_case(queried))
        .map(|(_, hint)| vec![hint.to_string()])
        .unwrap_or_default()
}

/// How close a registered name is to the one that failed: 0 for a case-only difference, 1 for a
/// prefix of the other, 2 for a near-miss, 3 for a long shared opening, -1 when unrelated.
pub fn name_rank(registered: &str, queried: &str) -> i32 {
    if registered.eq_ignore_ascii_case(queried) {
        return 0;
    }
    if registered.len() >= 3 && queried.len() >= 3 {
        let reg = registered.to_ascii_lowercase();
        let query = queried.to_ascii_lowercase();
        if reg.starts_with(&query) || query.starts_with(&reg) {
            return 1;
        }
        let tolerance = if registered.len().min(queried.len()) <= 4 { 1 } else { 2 };
        if edit_distance(&reg, &query) <= tolerance {
            return 2;
        }
    }
    if shared_prefix(registered, queried) >= 4 {
        3
    } else {
        -1
    }
}

fn shared_prefix(a: &str, b: &str) -> usize {
    a.chars()
        .zip(b.chars())
        .take_while(|(x, y)| x.eq_ignore_ascii_case(y))
        .count()
}

/// Levenshtein distance, capped: a length difference above two is far enough to be no suggestion.
fn edit_distance(a: &str, b: &str) -> usize {
    let a: Vec<char> = a.chars().collect();
    let b: Vec<char> = b.chars().collect();
    if a.len().abs_diff(b.len()) > 2 {
        return usize::MAX;
    }
    let mut previous: Vec<usize> = (0..=b.len()).collect();
    let mut current = vec![0usize; b.len() + 1];
    for i in 1..=a.len() {
        current[0] = i;
        for j in 1..=b.len() {
            let substitution =
                previous[j - 1] + usize::from(!a[i - 1].eq_ignore_ascii_case(&b[j - 1]));
            current[j] = (current[j - 1] + 1).min(previous[j] + 1).min(substitution);
        }
        std::mem::swap(&mut previous, &mut current);
    }
    previous[b.len()]
}
