#!/usr/bin/env node
// Generates parity/manifest.toml: one disposition row per census case.
//
// Rules:
//   - The census decides WHICH rows exist; a row that is not in the census is removed and a census
//     case with no row is added as "deferred". Nothing is silently dropped.
//   - A curated disposition comes from parity/manifest-map.json and always wins. A previous row is
//     preserved. Everything else defaults to "deferred" with an explicit reason: an unmapped test is
//     a known gap, not an absence.
//   - Only "ported" and "consolidated" claim Rust coverage; "deferred" and "excluded" do not.
import fs from 'node:fs';
import path from 'node:path';
import { parseToml } from './tools/toml.mjs';
import { readJson } from './tools/read.mjs';

const root = path.resolve(import.meta.dirname, '..');
const censusPath = path.join(root, 'parity', 'census.json');
const rustPath = path.join(root, 'parity', 'rust-tests.json');
const manifestPath = path.join(root, 'parity', 'manifest.toml');
const mapPath = path.join(root, 'parity', 'manifest-map.json');

if (!fs.existsSync(censusPath)) { console.error('missing parity/census.json: run the census tool first'); process.exit(2); }
const census = readJson(censusPath);
const rust = fs.existsSync(rustPath) ? readJson(rustPath) : { crates: [], suite: { exitCode: null } };
const curated = fs.existsSync(mapPath) ? JSON.parse(fs.readFileSync(mapPath, 'utf8')) : {};
const previous = fs.existsSync(manifestPath) ? parseToml(fs.readFileSync(manifestPath, 'utf8')) : { test: [] };
const prevById = new Map((previous.test || []).map(t => [t.id, t]));

const rows = [];
const seen = new Set();
for (const c of census.cases) {
  if (seen.has(c.id)) continue;
  seen.add(c.id);
  const cur = curated[c.id] || {};
  const prev = prevById.get(c.id) || {};
  const row = {
    id: c.id,
    project: c.project,
    disposition: cur.disposition || prev.disposition || 'deferred',
    rust: cur.rust || prev.rust || '',
    reason: cur.reason || prev.reason || 'No Rust test has been mapped to this capability yet.',
    targetPhase: cur.targetPhase !== undefined ? cur.targetPhase : (prev.targetPhase !== undefined ? prev.targetPhase : 0),
    note: cur.note || prev.note || '',
    owner: cur.owner || prev.owner || '',
  };
  if (row.disposition === 'ported' || row.disposition === 'consolidated') {
    row.reason = cur.reason || prev.reason || '';
  }
  rows.push(row);
}
rows.sort((a, b) => a.id.localeCompare(b.id, 'en'));

const esc = s => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
const lines = [
  '# Disposition of every C# test case in the census (TEST-007 / TEST-010).',
  '# Generated by parity/gen-manifest.mjs. Curate via parity/manifest-map.json, not by hand-editing',
  '# rows that the generator owns; a hand edit survives only until the next regeneration.',
  '',
  'schemaVersion = 1',
  'oracle = "' + census.oracle.commit + '"',
  'censusCases = ' + census.cases.length,
  '',
];
for (const r of rows) {
  lines.push('[[test]]');
  lines.push('id = "' + esc(r.id) + '"');
  lines.push('project = "' + esc(r.project) + '"');
  lines.push('disposition = "' + esc(r.disposition) + '"');
  if (r.rust) lines.push('rust = "' + esc(r.rust) + '"');
  if (r.reason) lines.push('reason = "' + esc(r.reason) + '"');
  lines.push('targetPhase = ' + Number(r.targetPhase || 0));
  if (r.note) lines.push('note = "' + esc(r.note) + '"');
  if (r.owner) lines.push('owner = "' + esc(r.owner) + '"');
  lines.push('');
}
fs.writeFileSync(manifestPath, lines.join('\n'));

const counts = {};
for (const r of rows) counts[r.disposition] = (counts[r.disposition] || 0) + 1;
const covered = (counts.ported || 0) + (counts.consolidated || 0);
console.log(JSON.stringify({ rows: rows.length, dispositions: counts, coveragePercent: rows.length ? +(100 * covered / rows.length).toFixed(2) : 0, rustTests: (rust.crates || []).reduce((n, c) => n + c.tests.length, 0) }, null, 2));
