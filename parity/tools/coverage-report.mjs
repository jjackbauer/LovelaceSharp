#!/usr/bin/env node
// Coverage report: census cases per project against the disposition each one actually has.
// Reads the generated manifest (not the curated map) so the numbers cannot drift from the gate.
import fs from 'node:fs';
import path from 'node:path';
import { parseToml } from './toml.mjs';
import { readJson } from './read.mjs';

const root = path.resolve(import.meta.dirname, '..', '..');
const census = readJson(path.join(root, 'parity', 'census.json'));
const manifest = parseToml(fs.readFileSync(path.join(root, 'parity', 'manifest.toml'), 'utf8'));
const projects = parseToml(fs.readFileSync(path.join(root, 'parity', 'projects.toml'), 'utf8'));

const rows = manifest.test || [];
const byProject = new Map();
for (const r of rows) {
  const p = byProject.get(r.project) || { cases: 0, ported: 0, consolidated: 0, deferred: 0, excluded: 0 };
  p.cases++;
  p[r.disposition] = (p[r.disposition] || 0) + 1;
  byProject.set(r.project, p);
}
const projectStatus = new Map((projects.project || []).map(p => [p.name, p.status]));
const lines = [
  '# Census coverage by project',
  '',
  'Generated by parity/tools/coverage-report.mjs from the manifest the gate reads. "Ported" means a',
  'census case resolves to a Rust test that exists in the measured inventory and whose suite ran green.',
  '',
  '| C# test project | Cases | Ported | Deferred | Excluded | Coverage | Project disposition |',
  '|---|---|---|---|---|---|---|',
];
let total = { cases: 0, ported: 0, deferred: 0, excluded: 0 };
const names = [...byProject.keys()].sort();
for (const name of names) {
  const p = byProject.get(name);
  total.cases += p.cases; total.ported += p.ported; total.deferred += p.deferred; total.excluded += p.excluded;
  const pct = p.cases ? ((100 * p.ported) / p.cases).toFixed(2) : '0.00';
  const status = projectStatus.get(name.replace(/\.Tests$/, '')) || '—';
  lines.push('| ' + name + ' | ' + p.cases + ' | ' + p.ported + ' | ' + p.deferred + ' | ' + p.excluded + ' | ' + pct + ' % | ' + status + ' |');
}
const totalPct = total.cases ? ((100 * total.ported) / total.cases).toFixed(2) : '0.00';
lines.push('| **TOTAL** | **' + total.cases + '** | **' + total.ported + '** | **' + total.deferred + '** | **' + total.excluded + '** | **' + totalPct + ' %** | |');
lines.push('');
lines.push('Proposed exclusions awaiting approval: parity/proposed-exclusions.toml (118 cases in four');
lines.push('projects with no Rust crate). They are NOT counted above: an exclusion the user has not');
lines.push('approved must not reduce the gap.');
fs.writeFileSync(path.join(root, 'parity', 'coverage.md'), lines.join('\n') + '\n');
console.log('coverage.md written: ' + total.ported + '/' + total.cases + ' ported (' + totalPct + '%)');
