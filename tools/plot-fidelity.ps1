using System;
using System.Drawing;
using System.Drawing.Drawing2D;
using System.Drawing.Imaging;
using System.Runtime.InteropServices;

public sealed class FidelityMetrics {
    public bool DimensionMatch;
    public int WidthA, HeightA, WidthB, HeightB;
    public long Pixels, Differing, DifferingStrict, SumAbsDiff, MaxDiff;
    public long InkA, InkB, InkUncoveredA, InkUncoveredB;
    public int DiffLeft, DiffTop, DiffRight, DiffBottom;
}

public static class Fidelity {
    public static Bitmap Load(string path) {
        var src = new Bitmap(path);
        var copy = new Bitmap(src.Width, src.Height, PixelFormat.Format32bppArgb);
        using (var g = Graphics.FromImage(copy)) {
            g.CompositingMode = CompositingMode.SourceCopy;
            g.DrawImageUnscaled(src, 0, 0);
        }
        src.Dispose();
        return copy;
    }

    static byte[] Bytes(Bitmap bmp, out int stride) {
        var rect = new Rectangle(0, 0, bmp.Width, bmp.Height);
        var data = bmp.LockBits(rect, ImageLockMode.ReadOnly, PixelFormat.Format32bppArgb);
        stride = data.Stride;
        var bytes = new byte[stride * bmp.Height];
        Marshal.Copy(data.Scan0, bytes, 0, bytes.Length);
        bmp.UnlockBits(data);
        return bytes;
    }

    public static FidelityMetrics Compare(string pathA, string pathB, int threshold, int strict, int inkLuminance, int radius) {
        var m = new FidelityMetrics();
        using (var a = Load(pathA))
        using (var b = Load(pathB)) {
            m.WidthA = a.Width; m.HeightA = a.Height;
            m.WidthB = b.Width; m.HeightB = b.Height;
            m.DimensionMatch = a.Width == b.Width && a.Height == b.Height;
            m.DiffLeft = a.Width; m.DiffTop = a.Height; m.DiffRight = -1; m.DiffBottom = -1;
            if (!m.DimensionMatch) { return m; }
            int w = a.Width, h = a.Height;
            m.Pixels = (long)w * h;
            int sa, sb;
            var ba = Bytes(a, out sa);
            var bb = Bytes(b, out sb);
            var inkA = new byte[w * h];
            var inkB = new byte[w * h];
            for (int y = 0; y < h; y++) {
                for (int x = 0; x < w; x++) {
                    int i = y * sa + x * 4;
                    int j = y * sb + x * 4;
                    int db = Math.Abs(ba[i + 0] - bb[j + 0]);
                    int dg = Math.Abs(ba[i + 1] - bb[j + 1]);
                    int dr = Math.Abs(ba[i + 2] - bb[j + 2]);
                    int d = Math.Max(db, Math.Max(dg, dr));
                    if (d > m.MaxDiff) { m.MaxDiff = d; }
                    m.SumAbsDiff += db + dg + dr;
                    if (d > threshold) {
                        m.Differing++;
                        if (x < m.DiffLeft) { m.DiffLeft = x; }
                        if (x > m.DiffRight) { m.DiffRight = x; }
                        if (y < m.DiffTop) { m.DiffTop = y; }
                        if (y > m.DiffBottom) { m.DiffBottom = y; }
                    }
                    if (d > strict) { m.DifferingStrict++; }
                    int la = (299 * ba[i + 2] + 587 * ba[i + 1] + 114 * ba[i + 0]) / 1000;
                    int lb = (299 * bb[j + 2] + 587 * bb[j + 1] + 114 * bb[j + 0]) / 1000;
                    if (la < inkLuminance) { inkA[y * w + x] = 1; m.InkA++; }
                    if (lb < inkLuminance) { inkB[y * w + x] = 1; m.InkB++; }
                }
            }
            // Integral image of B's ink so each A-ink pixel can ask "is any B ink within radius?"
            var integral = new long[(long)(w + 1) * (h + 1)];
            for (int y = 0; y < h; y++) {
                for (int x = 0; x < w; x++) {
                    long v = inkB[y * w + x];
                    integral[(long)(y + 1) * (w + 1) + (x + 1)] =
                        v + integral[(long)y * (w + 1) + (x + 1)] +
                        integral[(long)(y + 1) * (w + 1) + x] - integral[(long)y * (w + 1) + x];
                }
            }
            Func<int, int, int, long> box = delegate(int x, int y, int r) {
                int x0 = Math.Max(0, x - r), x1 = Math.Min(w - 1, x + r);
                int y0 = Math.Max(0, y - r), y1 = Math.Min(h - 1, y + r);
                return integral[(long)(y1 + 1) * (w + 1) + (x1 + 1)]
                    - integral[(long)y0 * (w + 1) + (x1 + 1)]
                    - integral[(long)(y1 + 1) * (w + 1) + x0]
                    + integral[(long)y0 * (w + 1) + x0];
            };
            for (int y = 0; y < h; y++) {
                for (int x = 0; x < w; x++) {
                    if (inkA[y * w + x] == 1 && box(x, y, radius) == 0) { m.InkUncoveredA++; }
                }
            }
            // Same question in reverse catches an element the product dropped entirely.
            var integralA = new long[(long)(w + 1) * (h + 1)];
            for (int y = 0; y < h; y++) {
                for (int x = 0; x < w; x++) {
                    long v = inkA[y * w + x];
                    integralA[(long)(y + 1) * (w + 1) + (x + 1)] =
                        v + integralA[(long)y * (w + 1) + (x + 1)] +
                        integralA[(long)(y + 1) * (w + 1) + x] - integralA[(long)y * (w + 1) + x];
                }
            }
            Func<int, int, int, long> boxA = delegate(int x, int y, int r) {
                int x0 = Math.Max(0, x - r), x1 = Math.Min(w - 1, x + r);
                int y0 = Math.Max(0, y - r), y1 = Math.Min(h - 1, y + r);
                return integralA[(long)(y1 + 1) * (w + 1) + (x1 + 1)]
                    - integralA[(long)y0 * (w + 1) + (x1 + 1)]
                    - integralA[(long)(y1 + 1) * (w + 1) + x0]
                    + integralA[(long)y0 * (w + 1) + x0];
            };
            for (int y = 0; y < h; y++) {
                for (int x = 0; x < w; x++) {
                    if (inkB[y * w + x] == 1 && boxA(x, y, radius) == 0) { m.InkUncoveredB++; }
                }
            }
        }
        return m;
    }

    public static void SaveComparison(string pathA, string pathB, string outPath, string labelA, string labelB, int threshold) {
        using (var a = Load(pathA))
        using (var b = Load(pathB)) {
            int gap = 8, header = 30;
            int w = a.Width * 3 + gap * 2;
            int h = header + a.Height;
            using (var canvas = new Bitmap(w, h, PixelFormat.Format32bppArgb))
            using (var g = Graphics.FromImage(canvas)) {
                g.Clear(Color.FromArgb(24, 28, 34));
                using (var font = new Font("Segoe UI", 12f, FontStyle.Bold, GraphicsUnit.Pixel))
                using (var brush = new SolidBrush(Color.FromArgb(216, 222, 233))) {
                    g.DrawString(labelA, font, brush, 4, 8);
                    g.DrawString(labelB, font, brush, a.Width + gap + 4, 8);
                    g.DrawString("difference > " + threshold + " (red)", font, brush, a.Width * 2 + gap * 2 + 4, 8);
                }
                g.DrawImageUnscaled(a, 0, header);
                g.DrawImageUnscaled(b, a.Width + gap, header);
                int sa, sb;
                var ba = Bytes(a, out sa);
                var bb = Bytes(b, out sb);
                using (var diff = new Bitmap(a.Width, a.Height, PixelFormat.Format32bppArgb)) {
                    var rect = new Rectangle(0, 0, diff.Width, diff.Height);
                    var data = diff.LockBits(rect, ImageLockMode.WriteOnly, PixelFormat.Format32bppArgb);
                    var outBytes = new byte[data.Stride * diff.Height];
                    for (int y = 0; y < a.Height; y++) {
                        for (int x = 0; x < a.Width; x++) {
                            int i = y * sa + x * 4;
                            int j = y * sb + x * 4;
                            int d = Math.Max(Math.Abs(ba[i] - bb[j]), Math.Max(Math.Abs(ba[i + 1] - bb[j + 1]), Math.Abs(ba[i + 2] - bb[j + 2])));
                            int o = y * data.Stride + x * 4;
                            if (d > threshold) {
                                outBytes[o + 0] = 60;
                                outBytes[o + 1] = 60;
                                outBytes[o + 2] = 255;
                            } else if (d > 0) {
                                outBytes[o + 0] = 110;
                                outBytes[o + 1] = 70;
                                outBytes[o + 2] = 70;
                            } else {
                                outBytes[o + 0] = 0;
                                outBytes[o + 1] = 0;
                                outBytes[o + 2] = 0;
                            }
                            outBytes[o + 3] = 255;
                        }
                    }
                    Marshal.Copy(outBytes, 0, data.Scan0, outBytes.Length);
                    diff.UnlockBits(data);
                    g.DrawImageUnscaled(diff, a.Width * 2 + gap * 2, header);
                }
                canvas.Save(outPath, ImageFormat.Png);
            }
        }
    }

    public static long CountNear(string path, int r, int g, int b, int tolerance) {
        using (var bmp = Load(path)) {
            int stride;
            var bytes = Bytes(bmp, out stride);
            long count = 0;
            for (int y = 0; y < bmp.Height; y++) {
                for (int x = 0; x < bmp.Width; x++) {
                    int i = y * stride + x * 4;
                    if (Math.Abs(bytes[i + 2] - r) <= tolerance &&
                        Math.Abs(bytes[i + 1] - g) <= tolerance &&
                        Math.Abs(bytes[i] - b) <= tolerance) { count++; }
                }
            }
            return count;
        }
    }
}
"@

