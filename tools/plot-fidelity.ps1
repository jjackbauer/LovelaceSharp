  <image href="$markerAbsolute" x="0" y="0" width="200" height="120"/>
  <rect id="marker" x="20" y="20" width="60" height="60" fill="#ffffff"/>
  <text x="20" y="105" font-family="sans-serif" font-size="14">safe content</text>
</svg>
"@
$controlPath = Join-Path $Corpus 'security-control.svg'
$hostilePath = Join-Path $Corpus 'security-hostile.svg'
$imageOnlyPath = Join-Path $Corpus 'security-image-only.svg'
[System.IO.File]::WriteAllText($controlPath, $controlSvg, $utf8)
[System.IO.File]::WriteAllText($hostilePath, $hostileSvg, $utf8)
[System.IO.File]::WriteAllText($imageOnlyPath, $imageOnlySvg, $utf8)

# ---------------------------------------------------------------------------
# Tolerance (fixed before measuring; the report explains each number)
# ---------------------------------------------------------------------------
$DiffThreshold = 16
$StrictThreshold = 64
$InkLuminance = 245
$InkRadius = 3
$MaxDiffPercent = 1.0
$MaxInkUncoveredPercent = 0.1

# ---------------------------------------------------------------------------
# Rasterise + compare the four corpus documents
# ---------------------------------------------------------------------------
$documentResults = @()
$failures = @()
foreach ($doc in $documents) {
    $name = $doc.Name
    $svg = $doc.Path
    $bytes = (Get-Item -LiteralPath $svg).Length
    $svgText = [System.IO.File]::ReadAllText($svg)
    $census = Get-Census $svgText
    $doc['Bytes'] = $bytes
    $doc['Sha256'] = Get-Sha256 $svg
    $doc['Census'] = $census

    $productPng = Join-Path $ProductDir "$name.png"
    $edgePng = Join-Path $EdgeDir "$name.png"
    Invoke-ProductRaster $svg $productPng $name | Out-Null
    $productSize = Get-PngSize $productPng
    $width = [int]($productSize.Split('x')[0])
    $height = [int]($productSize.Split('x')[1])
    $edgeSize = Invoke-EdgeShot $svg $edgePng $width $height $name
    if ($edgeSize -ne $productSize) {
        $failures += "$name dimensions differ: product $productSize, reference $edgeSize"
    }

    $metrics = [Fidelity]::Compare($productPng, $edgePng, $DiffThreshold, $StrictThreshold, $InkLuminance, $InkRadius)
    $diffPercent = if ($metrics.Pixels -gt 0) { 100.0 * $metrics.Differing / $metrics.Pixels } else { 100.0 }
    $diffStrictPercent = if ($metrics.Pixels -gt 0) { 100.0 * $metrics.DifferingStrict / $metrics.Pixels } else { 100.0 }
    $meanAbs = if ($metrics.Pixels -gt 0) { [double]$metrics.SumAbsDiff / ($metrics.Pixels * 3.0) } else { 0.0 }
    $inkUncoveredPercent = if ($metrics.InkA -gt 0 -or $metrics.InkB -gt 0) { 100.0 * ([Math]::Max($metrics.InkUncoveredA, $metrics.InkUncoveredB)) / [Math]::Max(1, [Math]::Max($metrics.InkA, $metrics.InkB)) } else { 0.0 }

    $comparePng = Join-Path $CompareDir "$name-compare.png"
    [Fidelity]::SaveComparison($productPng, $edgePng, $comparePng, "product resvg (${productSize})", "Edge ${BrowserVersion} (${edgeSize})", $DiffThreshold)

    $pass = $metrics.DimensionMatch -and ($diffPercent -le $MaxDiffPercent) -and ($inkUncoveredPercent -le $MaxInkUncoveredPercent)
    if (-not $pass) {
        $failures += ("$name fidelity failed: dimensions={0} diff>{1}={2:N4}% (limit {3}%) inkUncovered={4:N4}% (limit {5}%)" -f $metrics.DimensionMatch, $DiffThreshold, $diffPercent, $MaxDiffPercent, $inkUncoveredPercent, $MaxInkUncoveredPercent)
    }
    Write-Log ("compare {0} bytes={1} size={2} diff>{3}={4} ({5:N4}%) strict>{6}={7} ({8:N4}%) mae={9:N4} max={10} inkUncovered={11:N4}% pass={12}" -f $name, $bytes, $productSize, $DiffThreshold, $metrics.Differing, $diffPercent, $StrictThreshold, $metrics.DifferingStrict, $diffStrictPercent, $meanAbs, $metrics.MaxDiff, $inkUncoveredPercent, $pass)

    $documentResults += [ordered]@{
        name = $name
        kind = $doc.Kind
        source = $doc.Source
        svg = $svg
        svg_bytes = $bytes
        svg_sha256 = $doc.Sha256
        census = $census
        product_png = $productPng
        product_size = $productSize
        reference_png = $edgePng
        reference_size = $edgeSize
        compare_png = $comparePng
        metrics = [ordered]@{
            pixels = $metrics.Pixels
            differing_gt16 = $metrics.Differing
            differing_gt16_percent = [Math]::Round($diffPercent, 4)
            differing_gt64 = $metrics.DifferingStrict
            differing_gt64_percent = [Math]::Round($diffStrictPercent, 4)
            mean_abs_channel_diff = [Math]::Round($meanAbs, 4)
            max_channel_diff = $metrics.MaxDiff
            ink_a = $metrics.InkA
            ink_b = $metrics.InkB
            ink_uncovered_a = $metrics.InkUncoveredA
            ink_uncovered_b = $metrics.InkUncoveredB
            ink_uncovered_percent = [Math]::Round($inkUncoveredPercent, 4)
            diff_bbox = "$($metrics.DiffLeft),$($metrics.DiffTop)-$($metrics.DiffRight),$($metrics.DiffBottom)"
        }
        pass = $pass
    }
}

# ---------------------------------------------------------------------------
# Security result
# ---------------------------------------------------------------------------
$secControlPng = Join-Path $ProductDir 'security-control.png'
$secHostilePng = Join-Path $ProductDir 'security-hostile.png'
$secImageOnlyPng = Join-Path $ProductDir 'security-image-only.png'
Invoke-ProductRaster $controlPath $secControlPng 'security-control' | Out-Null
Invoke-ProductRaster $hostilePath $secHostilePng 'security-hostile' | Out-Null
Invoke-ProductRaster $imageOnlyPath $secImageOnlyPng 'security-image-only' | Out-Null

$productHostile = [Fidelity]::Compare($secControlPng, $secHostilePng, 0, 0, $InkLuminance, $InkRadius)
$productImageOnly = [Fidelity]::Compare($secControlPng, $secImageOnlyPng, 0, 0, $InkLuminance, $InkRadius)
$productMagenta = [Fidelity]::CountNear($secHostilePng, 255, 0, 255, 24)
$productPass = $productHostile.DimensionMatch -and $productHostile.Differing -eq 0 -and $productImageOnly.Differing -eq 0 -and $productMagenta -eq 0
if (-not $productPass) {
    $failures += ("security: product hostile/control differ={0} image-only/control differ={1} magenta={2}" -f $productHostile.Differing, $productImageOnly.Differing, $productMagenta)
}

$secEdgeControlPng = Join-Path $EdgeDir 'security-control.png'
$secEdgeHostilePng = Join-Path $EdgeDir 'security-hostile.png'
$secEdgeImageOnlyPng = Join-Path $EdgeDir 'security-image-only.png'
$size = Get-PngSize $secControlPng
$width = [int]($size.Split('x')[0])
$height = [int]($size.Split('x')[1])
Invoke-EdgeShot $controlPath $secEdgeControlPng $width $height 'security-control' | Out-Null
Invoke-EdgeShot $hostilePath $secEdgeHostilePng $width $height 'security-hostile' | Out-Null
Invoke-EdgeShot $imageOnlyPath $secEdgeImageOnlyPng $width $height 'security-image-only' | Out-Null
$edgeHostile = [Fidelity]::Compare($secEdgeControlPng, $secEdgeHostilePng, 0, 0, $InkLuminance, $InkRadius)
$edgeImageOnly = [Fidelity]::Compare($secEdgeControlPng, $secEdgeImageOnlyPng, 0, 0, $InkLuminance, $InkRadius)
$edgeMagenta = [Fidelity]::CountNear($secEdgeHostilePng, 255, 0, 255, 24)
$dom = Invoke-EdgeDom $hostilePath (Join-Path $Work 'security-hostile-dom.txt') 'security'
$edgeExecuted = $dom -match 'ff00ff'
Write-Log "security product hostileDiff=$($productHostile.Differing) imageOnlyDiff=$($productImageOnly.Differing) magenta=$productMagenta pass=$productPass"
Write-Log "security edge          hostileDiff=$($edgeHostile.Differing) imageOnlyDiff=$($edgeImageOnly.Differing) magenta=$edgeMagenta scriptInDom=$edgeExecuted"

[Fidelity]::SaveComparison($secControlPng, $secHostilePng, (Join-Path $CompareDir 'security-product-compare.png'), 'product: control', 'product: hostile SVG', 0) | Out-Null
[Fidelity]::SaveComparison($secEdgeControlPng, $secEdgeHostilePng, (Join-Path $CompareDir 'security-edge-compare.png'), 'Edge: control', 'Edge: hostile SVG', 0) | Out-Null

$securityResult = [ordered]@{
    control_svg = $controlPath
    hostile_svg = $hostilePath
    image_only_svg = $imageOnlyPath
    hostile_contains = [ordered]@{
        script = $true
        external_win_ini = $true
        file_uri_png = $true
        absolute_path_png = $true
    }
    product = [ordered]@{
        renderer = 'usvg 0.50 with the pane image resolver (string hrefs refused) + tiny-skia'
        control_png = $secControlPng
        hostile_png = $secHostilePng
        image_only_png = $secImageOnlyPng
        hostile_control_differing_pixels = $productHostile.Differing
        image_only_control_differing_pixels = $productImageOnly.Differing
        magenta_pixels = $productMagenta
        pass = $productPass
    }
    edge = [ordered]@{
        renderer = "Microsoft Edge $BrowserVersion (a browser, not the product renderer)"
        control_png = $secEdgeControlPng
        hostile_png = $secEdgeHostilePng
        image_only_png = $secEdgeImageOnlyPng
        hostile_control_differing_pixels = $edgeHostile.Differing
        image_only_control_differing_pixels = $edgeImageOnly.Differing
        magenta_pixels = $edgeMagenta
        dom_dump = (Join-Path $Work 'security-hostile-dom.txt')
        script_executed_in_dom = $edgeExecuted
    }
    note = 'The product refuses the external references and never runs the script (pixel-identical to the control). Edge, as a browser, loads the local file image and executes the script; that contrast is recorded, not used as the product criterion.'
}

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
$result = [ordered]@{
    round = 'round-29'
    generated_at = (Get-Date).ToString('o')
    product = [ordered]@{ exe = $Exe; sha256 = (Get-Sha256 $Exe); bytes = (Get-Item -LiteralPath $Exe).Length }
    engine_runner = [ordered]@{ exe = $Runner; sha256 = (Get-Sha256 $Runner) }
    reference_rasteriser = [ordered]@{ exe = $Browser; version = $BrowserVersion; flags = '--headless=new --disable-gpu --hide-scrollbars --force-device-scale-factor=1 --window-size=<W,H> --screenshot=<png> <file.svg>' }
    tolerance = [ordered]@{
        per_pixel_threshold = $DiffThreshold
        strict_threshold = $StrictThreshold
        max_diff_percent = $MaxDiffPercent
        ink_luminance_threshold = $InkLuminance
        ink_radius = $InkRadius
        max_ink_uncovered_percent = $MaxInkUncoveredPercent
    }
    reference = [ordered]@{ path = $referencePath; bytes = $referenceBytes; sha256 = (Get-Sha256 $referencePath); declared_bytes = 15000 }
    documents = $documentResults
    security = $securityResult
    failures = $failures
    passed = ($failures.Count -eq 0)
}
$jsonPath = Join-Path $OutDir 'fidelity.json'
[System.IO.File]::WriteAllText($jsonPath, ($result | ConvertTo-Json -Depth 12), $utf8)
Write-Log "wrote $jsonPath passed=$($result.passed)"

