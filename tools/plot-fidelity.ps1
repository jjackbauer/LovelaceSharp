  <script type="text/javascript">document.getElementById('marker').setAttribute('fill','#ff00ff');</script>
</svg>
"@
$imageOnlySvg = @"
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="200" height="120">
  <rect width="200" height="120" fill="#ffffff"/>
  <image xlink:href="file:///C:/Windows/win.ini" x="0" y="0" width="200" height="120"/>
