function Resolve-Browser([string]$Explicit) {
    $candidates = @()
    if ($Explicit) { $candidates += $Explicit }
    $candidates += @(
        (Join-Path ${env:ProgramFiles(x86)} 'Microsoft\Edge\Application\msedge.exe'),
        (Join-Path $env:ProgramFiles 'Microsoft\Edge\Application\msedge.exe'),
        (Join-Path $env:LOCALAPPDATA 'Microsoft\Edge\Application\msedge.exe'),
        (Join-Path ${env:ProgramFiles(x86)} 'Google\Chrome\Application\chrome.exe'),
        (Join-Path $env:ProgramFiles 'Google\Chrome\Application\chrome.exe')
    )
    foreach ($path in $candidates) {
        if ($path -and (Test-Path -LiteralPath $path)) {
            return $path
        }
    }
    throw 'No independent browser rasteriser found: install Microsoft Edge or Chrome (the harness refuses to skip the reference raster).'
}

function Invoke-ProductRaster([string]$Svg, [string]$Png, [string]$Tag) {
    if (Test-Path -LiteralPath $Png) { Remove-Item -LiteralPath $Png -Force }
    $stdout = Join-Path $Work "$Tag-product.stdout.txt"
    $stderr = Join-Path $Work "$Tag-product.stderr.txt"
    $process = Start-Process -FilePath $Exe -ArgumentList @('--raster-svg', $Svg, '--out', $Png) -Wait -PassThru -WindowStyle Hidden -RedirectStandardOutput $stdout -RedirectStandardError $stderr
    if ($process.ExitCode -ne 0) {
        throw "product raster failed for $Svg (exit $($process.ExitCode)): $((Get-Content -LiteralPath $stderr -Raw -ErrorAction SilentlyContinue))"
    }
    if (-not (Test-Path -LiteralPath $Png)) { throw "product raster produced no PNG: $Png" }
    $line = (Get-Content -LiteralPath $stdout -Raw).Trim()
    Write-Log "product $Tag $line"
    return $line
}

function Invoke-EdgeShot([string]$Svg, [string]$Png, [int]$Width, [int]$Height, [string]$Tag) {
    if (Test-Path -LiteralPath $Png) { Remove-Item -LiteralPath $Png -Force }
    $url = 'file:///' + ($Svg -replace '\\', '/')
    $profile = Join-Path $Work "edge-profile-$Tag"
    $stderr = Join-Path $Work "$Tag-edge.stderr.txt"
    $arguments = @(
        '--headless=new', '--disable-gpu', '--hide-scrollbars', '--force-device-scale-factor=1',
        '--no-first-run', '--disable-extensions', "--user-data-dir=$profile",
        "--window-size=$Width,$Height", "--screenshot=$Png", $url
    )
    $process = Start-Process -FilePath $Browser -ArgumentList $arguments -Wait -PassThru -WindowStyle Hidden -RedirectStandardError $stderr
    if ($process.ExitCode -ne 0) {
        throw "Edge screenshot failed for $Svg (exit $($process.ExitCode)): $((Get-Content -LiteralPath $stderr -Raw -ErrorAction SilentlyContinue))"
    }
    if (-not (Test-Path -LiteralPath $Png)) {
        Start-Sleep -Milliseconds 700
        if (-not (Test-Path -LiteralPath $Png)) { throw "Edge produced no screenshot for $Svg" }
    }
    $size = Get-PngSize $Png
    Write-Log "edge    $Tag file=$Png size=$size"
    return $size
}

function Get-PngSize([string]$Path) {
    $image = [System.Drawing.Image]::FromFile($Path)
    try { return "$($image.Width)x$($image.Height)" } finally { $image.Dispose() }
}

function Invoke-EdgeDom([string]$Svg, [string]$OutFile, [string]$Tag) {
    if (Test-Path -LiteralPath $OutFile) { Remove-Item -LiteralPath $OutFile -Force }
    $url = 'file:///' + ($Svg -replace '\\', '/')
    $profile = Join-Path $Work "edge-dom-$Tag"
    $arguments = @(
        '--headless=old', '--disable-gpu', '--no-first-run', '--disable-extensions',
        "--user-data-dir=$profile", '--virtual-time-budget=2000', '--dump-dom', $url
    )
    $process = Start-Process -FilePath $Browser -ArgumentList $arguments -Wait -PassThru -WindowStyle Hidden -RedirectStandardOutput $OutFile -RedirectStandardError (Join-Path $Work "$Tag-dom.stderr.txt")
    if ($process.ExitCode -ne 0) {
        throw "Edge --dump-dom failed for $Svg (exit $($process.ExitCode))"
    }
    return (Get-Content -LiteralPath $OutFile -Raw)
}

function Get-Census([string]$Svg) {
    $census = [ordered]@{}
    foreach ($tag in @('svg', 'rect', 'line', 'text', 'polyline', 'path', 'g', 'defs', 'clipPath', 'image', 'script')) {
        $census[$tag] = ([regex]::Matches($Svg, "<$tag\b")).Count
    }
    $census['clip'] = ($Svg -match 'clip-path=')
    $census['transform'] = ($Svg -match 'transform=')
    $census['dash'] = ($Svg -match 'stroke-dasharray=')
    $census['external_href'] = ($Svg -match '(xlink:)?href="(file|https?):')
    return $census
}

function Get-Sha256([string]$Path) {
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash
}

