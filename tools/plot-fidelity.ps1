<#
.SYNOPSIS
  Round-29 PLT-001/PLT-002 fidelity harness: rasterise the engine's SVG corpus with the product's
  resvg path and with an independent browser rasteriser, then report the measured difference.

.DESCRIPTION
  Corpus (all rasterised at their intrinsic 800x600 size, 1:1):
    ref-plot         the 15,000-byte SVG from the live C# Studio, extracted from
                     docs/goal-desktop-v4/reference/REF-plot.json;
    engine-square    generated by the Rust engine through lovelace-run plot(1..10, (1..10)^2, ...);
    engine-cubic     generated by the Rust engine, a negative/positive cubic with no title, so
                     the axes cross at zero and the tick labels differ from engine-square;
    feature-coverage a harness-derived document that embeds the engine-square polyline inside a
                     <g clip-path> with a translate, a dashed cubic <path> and a rotated <text>.
                     The current engine renderer emits only rect/line/text/polyline; this document
                     exists to exercise the path/clip/transform/dash features PLT-001/PLT-002 name.

  For each document:
    (a) the product   - lovelace-desktop.exe --raster-svg, i.e. the exact Plot::set_svg +
                        render_to_pixmap code the plot pane runs (system fonts + PLT-002 resolver);
    (b) the reference - headless Microsoft Edge (or Chrome) --screenshot at the same size.

  Metrics: pixel count, pixels differing by more than 16 (and by more than 64) on any RGB channel,
  mean absolute channel difference, and a structural ink-coverage check (ink = luminance < 245;
  radius 3) that flags a missing or displaced element even when antialiasing hides it in the raw
  count. Side-by-side + difference panels are written for each document.

  Security check: an SVG with <script> and external <image> references (a file:// URL, a file:// URL
  to a real local PNG, and a plain absolute path) is rendered through the same product path and
  compared pixel-for-pixel with a control document. Headless Edge renders the same pair so the
  report can state the browser's contrasting behaviour instead of implying it is the oracle.

  Windows PowerShell 5.1 compatible. ASCII-only.

.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File tools/plot-fidelity.ps1
  powershell -NoProfile -ExecutionPolicy Bypass -File tools/plot-fidelity.ps1 -Repo C:\Users\ricar\dev\LovelaceSharp
#>
