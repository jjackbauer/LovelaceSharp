        var sb = new StringBuilder();
        for (int i = 0; i < Gt.Length; i++)
        {
            using var scope = Real.WithPrecision(Places[i], Math.Min(Places[i], 40));
            Real pi = Real.PiTo(Places[i]);
            Real actual = Expr[i] switch
            {
                "Cos(PiTo(30))" or "Cos(PiTo(40))" or "Cos(PiTo(100))" => Real.Cos(pi),
                "Cos(PiTo(30)*2)" or "Cos(PiTo(40)*2)" or "Cos(PiTo(100)*2)" => Real.Cos(pi * new Real("2")),
                "Sin(PiTo(30))" or "Sin(PiTo(40))" or "Sin(PiTo(100))" => Real.Sin(pi),
                "Sin(PiTo(30)*2)" => Real.Sin(pi * new Real("2")),
                "Sin(PiTo(30)/2)" or "Sin(PiTo(40)/2)" or "Sin(PiTo(100)/2)" => Real.Sin(pi / new Real("2")),
                "Cos(PiTo(30)/3)" or "Cos(PiTo(40)/3)" or "Cos(PiTo(100)/3)" => Real.Cos(pi / new Real("3")),
                "Sin(PiTo(30)/6)" => Real.Sin(pi / new Real("6")),
                "Cos(PiTo(30)/4)" => Real.Cos(pi / new Real("4")),
                "Tan(PiTo(30)/4)" or "Tan(PiTo(40)/4)" or "Tan(PiTo(100)/4)" =>
                    Real.Divide(Real.Sin(pi / new Real("4")), Real.Cos(pi / new Real("4"))),
                _ => throw new InvalidOperationException(Expr[i]),
            };

            Real diff;
            using (Real.WithPrecision(6000, 30))
                diff = Real.Abs(actual - Real.Parse(Gt[i]));

            sb.AppendLine($"{Expr[i],-20} @{Places[i],3}  exact={actual.IsExact,-5} |actual-gt| = {Mag(diff)}   value={Mag(actual)}");
