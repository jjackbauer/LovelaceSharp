    /// <summary>The value as (sign)(14 leading digits) x 10^exponent, where the exponent is the
    /// value's own decimal exponent: the magnitude's leading digit sits at
    /// Exponent + Length − 1.</summary>
    private static string Mag(Real r)
    {
        if (Real.IsZero(r)) return "ZERO";
        string m = r.ToNatural().ToString();
        string head = m.Length > 14 ? m[..14] : m;
        long magnitudeExponent = r.Exponent + m.Length - 1;
        return (Int.IsNegative(r) ? "-" : "+") + head + " x10^" + magnitudeExponent;
    }

